#!/usr/bin/env node
/**
 * Regenerates `src/core/data/traditional-simplified.ts` from the vendored OpenCC
 * `TSCharacters.txt` dictionary (Apache-2.0, see THIRD_PARTY_NOTICES.md).
 *
 * Run this only when the vendored dictionary changes:
 *   node scripts/generate-tscharacters.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const input = resolve(root, 'data/vendor/opencc/TSCharacters.txt');
const output = resolve(root, 'src/core/data/traditional-simplified.ts');

const lines = readFileSync(input, 'utf8').split('\n');
const pairs = [];
for (const raw of lines) {
  const line = raw.replace(/\r$/, '').trim();
  if (line === '' || line.startsWith('#')) continue;
  const [key, value] = line.split('\t');
  if (!key || !value) continue;
  const first = value.split(' ')[0];
  if (!first) continue;
  if ([...key].length !== 1 || [...first].length !== 1) continue;
  if (key === first) continue;
  pairs.push(key + first);
}

const body = pairs.join('');
const banner = `/**
 * Traditional -> Simplified single-character mapping.
 *
 * Generated by \`scripts/generate-tscharacters.mjs\` from OpenCC's
 * \`data/dictionary/TSCharacters.txt\` (Apache-2.0). Do not edit by hand.
 * Entries are stored as alternating code points: traditional, simplified, ...
 * Only the first candidate of each OpenCC entry is kept, which is OpenCC's own
 * preferred mapping.
 */
export const TRADITIONAL_TO_SIMPLIFIED_PAIRS =
  ${JSON.stringify(body)};

/** Number of mapped characters. */
export const TRADITIONAL_TO_SIMPLIFIED_COUNT = ${pairs.length};
`;

writeFileSync(output, banner, 'utf8');
console.log(`wrote ${output} (${pairs.length} mappings)`);
